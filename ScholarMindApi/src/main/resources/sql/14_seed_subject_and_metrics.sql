SELECT '文献类别分布' AS item, literature_type AS name, COUNT(*) AS total
FROM literature WHERE deleted = 0 GROUP BY literature_type ORDER BY total DESC;

SELECT '学科分布' AS item, c.name AS name, COUNT(*) AS total
FROM literature l JOIN literature_category c ON c.id = l.category_id
WHERE l.deleted = 0 GROUP BY c.name ORDER BY total DESC;

SELECT '被引非零文献' AS item, COUNT(*) AS total FROM literature WHERE deleted = 0 AND citation_count > 0;
SELECT '有参考文献的文献' AS item, COUNT(*) AS total FROM literature WHERE deleted = 0 AND references_text IS NOT NULL AND references_text <> '';
SELECT '年度覆盖' AS item, COUNT(DISTINCT YEAR(publish_date)) AS total FROM literature WHERE deleted = 0 AND publish_date IS NOT NULL;
