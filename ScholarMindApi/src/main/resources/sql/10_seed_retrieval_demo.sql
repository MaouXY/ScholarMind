-- 第 2 批（A1）：检索演示文献扩充
-- 目标：让「自然语言检索 / 语义检索 / 混合检索」三种模式的差异可被观察到
-- 手法：
--   1) 12 篇已发布公开文献，分三类词面特征：
--      · 术语型（BM25 / k1 / 倒排索引 / DOI 等精确词）→ 稀疏召回占优
--      · 改写型（同一概念换说法，如「名次倒数累加」而不写 RRF）→ 向量召回占优
--      · 混合型（既有术语又有同义改写）→ 混合检索最稳
--   2) 每篇 3 个正文分块，分块文本手工撰写（不依赖原文文件解析），
--      因此这些文献刻意不绑定 file_id，重建索引时请只对需要验证的文献单独执行。
-- 特性：固定 ID + ON DUPLICATE KEY UPDATE，可重复执行
-- 执行：mysql -uroot -p --default-character-set=utf8mb4 scholar_mind < 10_seed_retrieval_demo.sql
-- 后续：执行后需调用一次 POST /api/v1/admin/rag/literature-vectors/rebuild 把分块写入 Milvus，
--       否则向量路不可用，混合检索会如实降级为稀疏检索（日志 vectorStoreStatus=DB_ONLY）。
-- ============================================================================

